#!/usr/bin/env node
// Labels every tests/*.test.mjs file for the Family Wall test inventory and
// writes tests/MANIFEST.md. Labels (see FAMILY_WALL_PLAN.md, P0.6):
//   keep                  - runs real code (imports it and checks results)
//   convert               - only reads source text; replace with a test that
//                           runs the code the next time that code is touched
//   retire-with:homepage  - pins old-homepage code the Wall will retire;
//                           delete in the same commit as that code
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const TESTS_DIR = 'tests'
const OLD_HOMEPAGE = [
  /components\/canvas\//,
  /heroFocus/,
  /useHeroIntelligence/,
  /useCalmKioskPresenter/,
  /SidecarCompanion/,
  /pointerGestures/,
  /pages\/HomePage/,
  /TurboCanvasView/,
  /CalmKioskView/,
]

function classify(source) {
  const importsCode = /^import\s[^'"]*from\s+['"]\.\.\/(src|supabase|scripts|pi)\//m.test(source)
    || /await import\(\s*['"]\.\.\/(src|supabase|scripts|pi)\//.test(source)
    || /execFileSync\(|spawnSync\(/.test(source)
  const readsSource = /readFileSync\(|readFile\(/.test(source)
  const readPaths = [...source.matchAll(/['"`](\.\.\/)?((src|supabase|scripts|pi)\/[^'"`]+)['"`]/g)].map((m) => m[2])
  const pinsOldHomepage = readPaths.some((p) => OLD_HOMEPAGE.some((re) => re.test(p)))
  if (pinsOldHomepage && !importsCode) return 'retire-with:homepage'
  if (importsCode) return 'keep'
  if (readsSource) return 'convert'
  return 'keep'
}

const files = readdirSync(TESTS_DIR).filter((f) => f.endsWith('.test.mjs')).sort()
const rows = files.map((file) => ({ file, label: classify(readFileSync(join(TESTS_DIR, file), 'utf8')) }))
const counts = rows.reduce((acc, r) => ({ ...acc, [r.label]: (acc[r.label] ?? 0) + 1 }), {})

const lines = [
  '# Test inventory',
  '',
  'Generated by `node scripts/test-manifest.mjs` — regenerate after adding or removing tests.',
  'Labels are a heuristic starting point (import/read patterns); correct any file by hand if wrong.',
  '',
  '| Label | Meaning | Count |',
  '|---|---|---|',
  `| keep | Runs real code | ${counts.keep ?? 0} |`,
  `| convert | Only reads source text; replace with a test that runs the code when that code is next touched | ${counts.convert ?? 0} |`,
  `| retire-with:homepage | Pins old-homepage code; delete in the same commit as that code (FAMILY_WALL_PLAN.md P5) | ${counts['retire-with:homepage'] ?? 0} |`,
  '',
  '| Test file | Label |',
  '|---|---|',
  ...rows.map((r) => `| ${r.file} | ${r.label} |`),
  '',
]
writeFileSync(join(TESTS_DIR, 'MANIFEST.md'), lines.join('\n'))
console.log(`${rows.length} files:`, counts)
