#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  DEFAULT_THEME_COLORS,
  DESIGN_TOKENS,
  MIDNIGHT_THEME_COLORS,
  THEME_COLOR_KEYS,
} from '../src/design-system/tokens.mjs'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(repoRoot, 'src/generated/design-tokens.css')

const declarations = (record, prefix) =>
  Object.entries(record).map(([key, value]) => `  --${prefix}-${key}: ${value};`)

function renderTheme() {
  const lines = [
    '/* Generated by scripts/generate-design-tokens.mjs. Do not edit directly. */',
    '',
    '@theme static {',
    ...declarations(DEFAULT_THEME_COLORS, 'color'),
    '  --color-casa-muted: var(--color-casa-text-tertiary);',
    '  --color-casa-divider: var(--color-casa-divider-strong);',
    ...declarations(DESIGN_TOKENS.staticColor, 'color'),
    ...declarations(DESIGN_TOKENS.fontFamily, 'font'),
  ]

  for (const [key, token] of Object.entries(DESIGN_TOKENS.type)) {
    lines.push(`  --text-${key}: var(--ds-type-${key});`)
    lines.push(`  --text-${key}--line-height: ${token.lineHeight};`)
  }

  lines.push(
    '  --ds-font-scale: 1;',
    ...declarations(DESIGN_TOKENS.radius, 'radius'),
    ...declarations(DESIGN_TOKENS.shadow, 'shadow'),
    ...declarations(DESIGN_TOKENS.spacing, 'spacing'),
    ...declarations(DESIGN_TOKENS.container, 'container'),
    '  --spacing-control: var(--ds-control-target);',
    '  --spacing-control-sm: var(--ds-control-sm);',
    '  --spacing-control-md: var(--ds-control-md);',
    '  --spacing-control-lg: var(--ds-control-lg);',
    ...declarations(DESIGN_TOKENS.motion, 'transition'),
    ...declarations(DESIGN_TOKENS.zIndex, 'z-index'),
    '  --animate-fade-in: fade-in 0.3s ease-out;',
    '  --animate-slide-up: slide-up 0.35s ease-out;',
    '  --animate-pulse-gold: pulse-gold 2s ease-in-out infinite;',
    '  --animate-breathe: breathe 3s ease-in-out infinite;',
    '}',
    '',
    ':root {',
    `  --ds-page-gutter: ${DESIGN_TOKENS.layout.gutterPhone};`,
    '}',
    '',
    `@media (min-width: ${DESIGN_TOKENS.layout.breakpointTablet}) {`,
    '  :root {',
    `    --ds-page-gutter: ${DESIGN_TOKENS.layout.gutterTablet};`,
    '  }',
    '}',
    '',
    `@media (min-width: ${DESIGN_TOKENS.layout.breakpointWide}) {`,
    '  :root {',
    `    --ds-page-gutter: ${DESIGN_TOKENS.layout.gutterWide};`,
    '  }',
    '}',
    '',
    ':root,',
    'html[data-density="touch"] {',
  )

  for (const [key, token] of Object.entries(DESIGN_TOKENS.type)) {
    lines.push(`  --ds-type-${key}: calc(${token.touch} * var(--ds-font-scale));`)
  }
  for (const [key, value] of Object.entries(DESIGN_TOKENS.controls.touch)) {
    lines.push(`  --ds-control-${key}: ${value};`)
  }

  lines.push('}', '', 'html[data-density="compact"] {')
  for (const [key, token] of Object.entries(DESIGN_TOKENS.type)) {
    lines.push(`  --ds-type-${key}: calc(${token.compact} * var(--ds-font-scale));`)
  }
  for (const [key, value] of Object.entries(DESIGN_TOKENS.controls.compact)) {
    lines.push(`  --ds-control-${key}: ${value};`)
  }

  lines.push('}', '', 'html[data-density="kiosk"] {')
  for (const [key, token] of Object.entries(DESIGN_TOKENS.type)) {
    lines.push(`  --ds-type-${key}: calc(${token.kiosk} * var(--ds-font-scale));`)
  }
  for (const [key, value] of Object.entries(DESIGN_TOKENS.controls.kiosk)) {
    lines.push(`  --ds-control-${key}: ${value};`)
  }

  lines.push('}', '', 'html.midnight-gallery {')
  for (const key of THEME_COLOR_KEYS) {
    lines.push(`  --color-${key}: ${MIDNIGHT_THEME_COLORS[key]};`)
  }
  lines.push(
    '  --color-casa-muted: var(--color-casa-text-tertiary);',
    '  --color-casa-divider: var(--color-casa-divider-strong);',
    ...declarations(DESIGN_TOKENS.midnightShadow, 'shadow'),
    '}',
    '',
  )

  return lines.join('\n')
}

const expected = renderTheme()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(outputPath, 'utf8')
  } catch {
    // The actionable error below covers a missing generated file.
  }
  if (current !== expected) {
    console.error('Generated design tokens are stale. Run `npm run tokens:generate` and commit the result.')
    process.exitCode = 1
  } else {
    console.log('Design token CSS is current.')
  }
} else {
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, expected)
  console.log('Generated src/generated/design-tokens.css')
}
